#!/usr/bin/env node
/* ==========================================================================
   generate-palette.js — the single source of truth for colour.

   Reads the design tokens export (design/Light theme.tokens.json) and writes
   assets/css/palette.css: every step of every ramp as a CSS custom property,
   e.g. --iron-600, --navy-800, --grey-100.

   Never edit palette.css by hand. To change a colour, update the tokens JSON
   and run:  node scripts/generate-palette.js
   ========================================================================== */
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "..", "design", "Light theme.tokens.json");
const OUT = path.join(__dirname, "..", "assets", "css", "palette.css");

// Token ramp name -> CSS prefix
const PREFIX = {
  "Iron Oxide": "iron", "Slate Navy": "navy", "Golden Sandstone": "gold",
  "Neutral Grey": "grey", "Sage Green": "sage", "Soft Rose": "rose",
};

const tokens = JSON.parse(fs.readFileSync(SRC, "utf8"));
let css = "/* Generated by scripts/generate-palette.js from design/Light theme.tokens.json.\n   Do not edit by hand. */\n:root {\n";
for (const [ramp, prefix] of Object.entries(PREFIX)) {
  if (!tokens[ramp]) throw new Error("Missing ramp in tokens: " + ramp);
  const steps = Object.entries(tokens[ramp]).filter(([k, v]) => !k.startsWith("$") && v && (v.$value || v.value));
  steps.sort((a, b) => Number(a[0]) - Number(b[0]));
  css += `\n  /* ${ramp} */\n`;
  for (const [step, v] of steps) {
    const val = v.$value || v.value;
    const hex = typeof val === "string" ? val : val.hex;
    css += `  --${prefix}-${Number(step)}: ${hex.toUpperCase()};\n`;
  }
}
css += "}\n";
fs.writeFileSync(OUT, css);
console.log("Wrote", path.relative(process.cwd(), OUT));
